async page => {
  const SP = 'captures/';
  const log = []; const errs = [];
  page.on('pageerror', e => errs.push(String(e)));
  await page.goto('http://localhost:5182/');
  await page.evaluate(() => localStorage.clear());
  await page.goto('http://localhost:5182/connexion');
  await page.waitForTimeout(2200);
  await page.click('.cx-compte:has-text("Fabien")');
  await page.click('button[type=submit]');
  await page.waitForTimeout(3000);
  await page.click('.case >> nth=0'); await page.click('.case >> nth=1');
  await page.click('text=Continuer');
  await page.waitForTimeout(3000);
  log.push('connecté ' + page.url());
  const sw = await page.evaluate(async () => { const r = await navigator.serviceWorker.ready; return !!r.active && r.active.state; });
  log.push('sw ' + sw);
  await page.reload();
  await page.waitForTimeout(2500);
  log.push('controller ' + await page.evaluate(() => !!navigator.serviceWorker.controller));
  const man = await page.evaluate(async () => { const m = await (await fetch('/manifest.webmanifest')).json(); const ic = await Promise.all(m.icons.map(async i => i.src + ':' + (await fetch('/' + i.src)).status)); return m.name + ' | ' + ic.join(' ') });
  log.push('manifest ' + man);
  await page.context().setOffline(true);
  await page.goto('http://localhost:5182/');
  await page.waitForTimeout(3000);
  log.push('hors ligne: ' + page.url() + ' hero=' + await page.evaluate(() => document.querySelector('.hero-w')?.textContent) + ' | pastille=' + await page.evaluate(() => document.querySelector('.hors-connexion')?.textContent.trim()));
  await page.screenshot({ path: SP + 'l9-offline-dash.png' });
  await page.goto('http://localhost:5182/seance/w-fabien-2?nouvelle=1');
  await page.waitForTimeout(3000);
  const action = page.locator('.panel:not([inert]) [data-action]');
  log.push('séance hors ligne: ' + (await action.first().textContent()).trim());
  await action.first().click();
  await page.waitForTimeout(1500);
  await page.screenshot({ path: SP + 'l9-offline-seance.png' });
  await page.context().setOffline(false);
  await page.waitForTimeout(1500);
  log.push('errs ' + JSON.stringify(errs));
  return log.join('\n');
}
